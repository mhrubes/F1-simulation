export const MESSAGES: Record<Locale, MessageDict> = { cs, en, sk };

export function formatLapTime(seconds: number, locale: Locale): string {
  const m = Math.floor(seconds / 60);
  const s = Math.round(seconds % 60);
  const minLabel = MESSAGES[locale]["units.min"];
  const secLabel = MESSAGES[locale]["units.sec"];
  return `${m} ${minLabel} ${s.toString().padStart(2, "0")} ${secLabel}`;
}
